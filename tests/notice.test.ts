import { test } from 'node:test';
import assert from 'node:assert/strict';
import { openDb, nowIso } from '../src/db.ts';
import { markCaptureCompleted } from '../src/store.ts';
import { issueAssignmentNotice, assignmentNoticeText, storedNotice, noticeDigestMatches, recordNoticeService, noticeServiceLog, noticeServiceRegister, noticeServiceCsv } from '../src/notice.ts';

function book(status = 'funded', captureStatus: string | null = null) {
  const db = openDb(':memory:');
  const at = nowIso();
  db.prepare("INSERT INTO sellers (id, paypal_merchant_id, legal_name, country, created_at) VALUES ('s1','seller@example.com','Northwind Components LLC','US',?)").run(at);
  db.prepare('INSERT INTO debtors (id, legal_name, normalized_name, billing_address_json, limit_cents, created_at) VALUES (?,?,?,?,?,?)')
    .run('d1', 'Halcyon Industries', 'halcyon', JSON.stringify({ line1: '18 Rigging Rd', city: 'Austin', region: 'TX', postalCode: '78701', countryCode: 'US' }), 1_000_000, at);
  db.prepare("INSERT INTO funders (id, legal_name, paypal_email, created_at) VALUES ('f1','Sandbox Funder','funder@example.com',?)").run(at);
  db.prepare(`INSERT INTO invoices (id, invoice_number, seller_id, debtor_id, face_cents, currency, issued_on, due_on, status, created_at)
              VALUES ('inv_1','NW-1','s1','d1',65000,'USD','2026-10-01','2026-11-30',?,?)`).run(status, at);
  db.prepare("INSERT INTO slices (id, invoice_id, funder_id, share_bp, principal_cents, status, created_at) VALUES ('sl_1','inv_1','f1',10000,49301,'paid',?)").run(at);
  if (captureStatus !== null) {
    // One status per capture, beside the capture id it belongs to, which is how the column is stored.
    const ids = captureStatus.split(',').map((_, index) => `cap_${index + 1}`).join(',');
    db.prepare(`INSERT INTO commitments (id, slice_id, paypal_order_id, capture_id, capture_status, amount_cents, status, created_at)
                VALUES ('cm_1','sl_1','ORDER1',?,?,49301,'captured',?)`).run(ids, captureStatus, at);
  }
  return db;
}

test('a receivable bought in part has not been assigned cleanly, so the debtor is not told yet', () => {
  assert.equal(assignmentNoticeText(book('partially_funded'), 'inv_1'), null);
  assert.equal(issueAssignmentNotice(book('partially_funded'), 'inv_1'), null);
  assert.equal(storedNotice(book('partially_funded'), 'inv_1'), null);
});

test('the notice says who holds the paper now and where the debtor must pay', () => {
  const db = book();
  const issued = issueAssignmentNotice(db, 'inv_1', '2026-10-30')!;
  const body = issued.bodyText;
  assert.match(body, /NOTICE OF ASSIGNMENT OF A RECEIVABLE/);
  assert.match(body, /Halcyon Industries/);
  assert.match(body, /invoice NW-1, issued 2026-10-01 by Northwind Components LLC, \$650\.00 due 2026-11-30/);
  assert.match(body, /Sandbox Funder — advance of \$493\.01/);
  assert.match(body, /18 Rigging Rd, Austin, TX, 78701, US/);
  assert.match(body, /a payment made to them does not discharge what you owe/);
  assert.match(body, /Do not pay the seller directly/);
  // It also says what it is not, because a document generated by a hackathon build should not dress
  // itself up as a statutory form.
  assert.match(body, /not a demand, a court filing, or legal advice/);
  assert.match(body, /this build does not model those rules/);
});

test('the stored bytes are the hashed bytes, once and only once', () => {
  const db = book();
  const issued = issueAssignmentNotice(db, 'inv_1')!;
  assert.equal(issueAssignmentNotice(db, 'inv_1'), null, 'a second funding is a re-assignment, not a reminder');
  assert.equal(Number((db.prepare('SELECT COUNT(*) AS n FROM notices').get() as any).n), 1);
  assert.equal(noticeDigestMatches(db, 'inv_1'), true);
  const audit = db.prepare("SELECT * FROM audit_log WHERE subject_id = 'inv_1' AND kind = 'notice_of_assignment'").get() as any;
  assert.ok(audit, 'the notice is in the chain');
  assert.equal(JSON.parse(audit.payload_json).sha256, issued.sha256);
  assert.equal(JSON.parse(audit.payload_json).addressee, 'Halcyon Industries');
});

test('a notice edited after the day it went out is caught by its own digest', () => {
  const db = book();
  issueAssignmentNotice(db, 'inv_1')!;
  // The ledger is trigger-protected; this table is not, so the digest is what proves it here.
  db.prepare("UPDATE notices SET body_text = body_text || ' ' WHERE invoice_id = 'inv_1'").run();
  assert.equal(noticeDigestMatches(db, 'inv_1'), false);
});

test('the desk can write down that it served the notice, and what bytes went out', () => {
  const db = book();
  const issued = issueAssignmentNotice(db, 'inv_1')!;
  const entry = recordNoticeService(db, 'inv_1', {
    channel: 'Recorded delivery, UK', reference: ' TW059301341GB ', servedAt: '2026-10-30', enteredBy: 'desk'
  })!;
  assert.equal(entry.channel, 'Recorded delivery, UK');
  assert.equal(entry.reference, 'TW059301341GB', 'what the operator typed is stored as they typed it, trimmed');
  assert.equal(entry.servedAt, '2026-10-30');
  // The digest is the notice's own, recomputed from the stored bytes — not a value the form supplied.
  assert.equal(entry.digest, issued.sha256);
  assert.deepEqual(noticeServiceLog(db, 'inv_1').map((e) => e.reference), ['TW059301341GB']);
  const audit = db.prepare("SELECT payload_json FROM audit_log WHERE subject_id = 'inv_1' AND kind = 'notice_served'").get() as any;
  assert.equal(JSON.parse(audit.payload_json).digest, issued.sha256);
  assert.equal(JSON.parse(audit.payload_json).enteredBy, 'desk');
});

test('a second attempt is a new entry, not an edit of the first', () => {
  const db = book();
  issueAssignmentNotice(db, 'inv_1')!;
  recordNoticeService(db, 'inv_1', { channel: 'Email to the accounts contact', enteredBy: 'desk' })!;
  recordNoticeService(db, 'inv_1', { channel: 'Recorded delivery, UK', reference: 'TW059301341GB', enteredBy: 'desk' })!;
  const log = noticeServiceLog(db, 'inv_1');
  assert.equal(log.length, 2);
  assert.deepEqual(log.map((e) => e.channel), ['Email to the accounts contact', 'Recorded delivery, UK']);
});

test('the register cannot be quietly amended', () => {
  const db = book();
  issueAssignmentNotice(db, 'inv_1')!;
  const entry = recordNoticeService(db, 'inv_1', { channel: 'Courier', enteredBy: 'desk' })!;
  assert.throws(() => db.prepare("UPDATE notice_service SET channel = 'Registered letter' WHERE id = ?").run(entry.id), /append-only/);
  assert.throws(() => db.prepare('DELETE FROM notice_service WHERE id = ?').run(entry.id), /append-only/);
});

test('nothing is served on a notice that no longer matches itself', () => {
  const db = book();
  issueAssignmentNotice(db, 'inv_1')!;
  db.prepare("UPDATE notices SET body_text = body_text || ' ' WHERE invoice_id = 'inv_1'").run();
  assert.throws(
    () => recordNoticeService(db, 'inv_1', { channel: 'Courier', enteredBy: 'desk' }),
    /no longer matches its own digest/
  );
  assert.equal(noticeServiceLog(db, 'inv_1').length, 0);
});

test('an invoice the desk has not told yet has no register', () => {
  const db = book('partially_funded');
  assert.equal(recordNoticeService(db, 'inv_1', { channel: 'Courier', enteredBy: 'desk' }), null);
  assert.deepEqual(noticeServiceLog(db, 'inv_1'), []);
});

test('the notice tells the debtor what the rail said the day it went out', () => {
  assert.match(assignmentNoticeText(book('funded', 'PENDING'), 'inv_1')!, /reports the capture of the advance as PENDING/);
  assert.match(assignmentNoticeText(book('funded', 'PENDING'), 'inv_1')!, /as PENDING\. If that capture\n   does not clear, the purchase it pays for is reversed/);
  assert.match(assignmentNoticeText(book('funded', 'COMPLETED'), 'inv_1')!, /every capture of the advance as COMPLETED/);
  // Nothing in the sandbox ever cleared, so the shipped demo book reads the first of those two lines.
  // A notice that claimed settlement the rail had not confirmed would be the desk inventing its own title.
  assert.match(assignmentNoticeText(book(), 'inv_1')!, /No capture is recorded on the rail for this advance/);
});

test('the webhook updates the desk, and the document keeps the words it was issued with', () => {
  const db = book('funded', 'PENDING');
  const issued = issueAssignmentNotice(db, 'inv_1')!;
  assert.equal(markCaptureCompleted(db, 'cap_1'), 1);
  assert.equal((db.prepare("SELECT capture_status FROM commitments WHERE id = 'cm_1'").get() as any).capture_status, 'COMPLETED');
  // The bytes the debtor was sent are immutable and still hashed, so a later clearance cannot rewrite
  // the document — only the desk's live answer about the same capture.
  assert.match(storedNotice(db, 'inv_1')!.body_text, /as PENDING/);
  assert.equal(noticeDigestMatches(db, 'inv_1'), true);
  assert.match(assignmentNoticeText(db, 'inv_1')!, /every capture of the advance as COMPLETED/);
  assert.ok(db.prepare("SELECT id FROM audit_log WHERE kind = 'funding_capture_completed' AND subject_id = 'inv_1'").get(), 'the clearance is on the chain');
});

test('a capture id this desk never booked marks nothing', () => {
  const db = book('funded', 'PENDING');
  assert.equal(markCaptureCompleted(db, 'cap_nobody'), 0);
  assert.equal((db.prepare("SELECT capture_status FROM commitments WHERE id = 'cm_1'").get() as any).capture_status, 'PENDING');
  assert.equal(markCaptureCompleted(db, ''), 0);
});

test('half a funding clearing is not the funding cleared', () => {
  const db = book('funded', 'PENDING,PENDING');
  assert.equal(markCaptureCompleted(db, 'cap_1'), 1);
  assert.equal((db.prepare("SELECT capture_status FROM commitments WHERE id = 'cm_1'").get() as any).capture_status, 'COMPLETED,PENDING');
  // The second unit still owes its answer, so a notice written now cannot read as settled.
  assert.match(assignmentNoticeText(db, 'inv_1')!, /reports the capture of the advance as PENDING/);
  assert.equal(markCaptureCompleted(db, 'cap_2'), 1);
  assert.match(assignmentNoticeText(db, 'inv_1')!, /every capture of the advance as COMPLETED/);
});

test('a capture whose status the rail never sent is not a clearance either', () => {
  const db = book('funded', 'COMPLETED,');
  assert.match(assignmentNoticeText(db, 'inv_1')!, /reports the capture of the advance as not reported/);
  assert.equal(markCaptureCompleted(db, 'cap_2'), 1, 'the rail is allowed to answer a capture it had not answered');
  assert.match(assignmentNoticeText(db, 'inv_1')!, /every capture of the advance as COMPLETED/);
});


test('the register exports as one file, in the order the notices went out', () => {
  const db = book();
  const issued = issueAssignmentNotice(db, 'inv_1')!;
  recordNoticeService(db, 'inv_1', { channel: 'Recorded delivery, UK', reference: 'TW059301341GB', servedAt: '2026-10-30', enteredBy: 'desk' })!;
  recordNoticeService(db, 'inv_1', { channel: 'Email to the accounts contact', servedAt: '2026-11-02', enteredBy: 'ops' })!;
  const rows = noticeServiceRegister(db);
  assert.deepEqual(rows.map((r) => r.servedAt), ['2026-10-30', '2026-11-02'], 'a register a reader can check for gaps is ordered by when it says it went');
  assert.deepEqual(rows.map((r) => r.enteredBy), ['desk', 'ops']);
  assert.equal(rows[0].invoiceNumber, 'NW-1');
  assert.equal(rows[0].debtorName, 'Halcyon Industries');
  assert.equal(rows[0].digest, issued.sha256);
  assert.equal(rows[0].digestStillMatches, true);

  const csv = noticeServiceCsv(db);
  const lines = csv.trimEnd().split('\r\n');
  assert.equal(lines[0], '"served_on","invoice_number","debtor","notice_id","channel","reference","attested_by","recorded_at","sha256_of_notice_bytes","bytes_still_match"', 'every field is quoted, header included — one shape for the whole file');
  assert.equal(lines.length, 3, 'one line per entry, plus the header');
  assert.match(lines[1], /^"2026-10-30","NW-1","Halcyon Industries","note_.+","Recorded delivery, UK","TW059301341GB","desk"/);
  assert.match(lines[2], /"Email to the accounts contact","",/, 'an empty reference stays an empty field, not the word null');
  assert.match(lines[2], new RegExp(`"${issued.sha256}","yes"$`));
});

test('an entry made before the notice was edited says so on the way out', () => {
  const db = book();
  issueAssignmentNotice(db, 'inv_1')!;
  recordNoticeService(db, 'inv_1', { channel: 'Courier', enteredBy: 'desk' })!;
  // The register itself cannot be amended, but the notice can be — and then the file has to say that
  // the bytes it certifies are no longer the bytes on the page.
  db.prepare("UPDATE notices SET body_text = body_text || ' ' WHERE invoice_id = 'inv_1'").run();
  const rows = noticeServiceRegister(db);
  assert.equal(rows.length, 1);
  assert.equal(rows[0].digestStillMatches, false);
  assert.match(noticeServiceCsv(db), /"NO - EDITS AFTER THIS ENTRY"/);
});

test('a reference typed by someone else does not become a formula in the auditor’s spreadsheet', () => {
  const db = book();
  issueAssignmentNotice(db, 'inv_1')!;
  recordNoticeService(db, 'inv_1', {
    channel: 'Portal', reference: '=HYPERLINK("http://desk.example","click")', enteredBy: 'desk'
  })!;
  recordNoticeService(db, 'inv_1', { channel: '+CMD', reference: '-1,calc', enteredBy: 'desk' })!;
  // The newline case: a quoted cell whose content starts with a line break, so the formula
  // character is not the first byte of the cell — spreadsheets read it anyway.
  recordNoticeService(db, 'inv_1', { channel: '\n=WEBSERVICE("http://desk.example")', reference: 'ok', enteredBy: 'desk' })!;
  const csv = noticeServiceCsv(db);
  assert.ok(
    csv.includes(`"'=HYPERLINK(""http://desk.example"",""click"")"`),
    'the leading operator is neutralised and the inner quotes are doubled'
  );
  assert.ok(csv.includes(`"'+CMD","'-1,calc"`), 'every character a spreadsheet reads as a formula gets the same treatment');
  assert.ok(csv.includes("'\n=WEBSERVICE(\"http://desk.example\")"), 'a cell that begins with a newline is neutralised too');
  assert.doesNotMatch(csv, /,"=/, 'no cell reaches a spreadsheet as a live formula');
});
